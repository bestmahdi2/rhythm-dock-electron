'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const pkg=require('../package.json');
assert.equal(pkg.build.nsis.oneClick,false);
assert.equal(pkg.build.nsis.allowToChangeInstallationDirectory,true);
assert.equal(pkg.build.nsis.deleteAppDataOnUninstall,false);
assert.equal(pkg.build.appId,'com.masterous.rhythmdock');
const include=fs.readFileSync(path.join(__dirname,'..',pkg.build.nsis.include),'utf8');
for(const marker of ['MUI_PAGE_WELCOME','RhythmSetupGuide','lyrics.db','RhythmDockData'])assert.ok(include.includes(marker));
const source=fs.readFileSync(path.join(__dirname,'../src/main/services/database.js'),'utf8');
const migration=source.slice(source.indexOf('function runMigrations('),source.indexOf('/**\n * Opens (never recreates)'));
let writes=0,backups=0;
const context={TARGET_VERSION:2,console,backupDatabase:()=>{backups++;return null;},MIGRATIONS:[()=>writes++,()=>writes++]};
vm.createContext(context);vm.runInContext(migration,context);
const handle={pragma:()=>1,transaction:callback=>()=>{writes++;callback();}};
assert.throws(()=>context.runMigrations(handle,'existing.db'),/safety backup/);
assert.equal(writes,0,'failed backup must prevent all migration writes');
assert.equal(backups,1);
context.backupDatabase=()=>'/backup/existing.db';
context.runMigrations(handle,'existing.db');assert.ok(writes>0);
console.log('PASS: guided installer, stable app identity, preserved app data and backup-required database migrations');
